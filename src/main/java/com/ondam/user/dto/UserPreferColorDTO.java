package com.ondam.user.dto;

public class UserPreferColorDTO {
		private int userPreferColorNo;
		private int userNo;
		private String preferColor;
		
		public int getUserPreferColorNo() {
			return userPreferColorNo;
		}
		public void setUserPreferColorNo(int userPreferColorNo) {
			this.userPreferColorNo = userPreferColorNo;
		}
		public int getUserNo() {
			return userNo;
		}
		public void setUserNo(int userNo) {
			this.userNo = userNo;
		}
		public String getPreferColor() {
			return preferColor;
		}
		public void setPreferColor(String preferColor) {
			this.preferColor = preferColor;
		}
}
