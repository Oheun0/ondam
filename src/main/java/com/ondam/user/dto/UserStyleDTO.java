package com.ondam.user.dto;

public class UserStyleDTO {
	private int userStyleNo;
	private int userNo;
	private String userPreferStyle;
	
	public int getUserStyleNo() {
		return userStyleNo;
	}
	public void setUserStyleNo(int userStyleNo) {
		this.userStyleNo = userStyleNo;
	}
	public int getUserNo() {
		return userNo;
	}
	public void setUserNo(int userNo) {
		this.userNo = userNo;
	}
	public String getUserPreferStyle() {
		return userPreferStyle;
	}
	public void setUserPreferStyle(String userPreferStyle) {
		this.userPreferStyle = userPreferStyle;
	}
}
